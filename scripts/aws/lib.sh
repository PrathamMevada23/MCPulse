#!/usr/bin/env bash
#
# Shared helpers for the MCPulse AWS Learner Lab scripts.
#
# Every script is idempotent: it inspects the current state first and only
# creates or changes what is actually missing. Nothing is ever deleted.

set -euo pipefail

# ---------------------------------------------------------------- configuration

: "${AWS_PROFILE:=learnerlab}"
: "${AWS_REGION:=us-east-1}"
: "${PROJECT_NAME:=mcpulse}"
: "${DB_IDENTIFIER:=mcpulse-db}"
: "${DB_NAME:=mcpulse}"
: "${DB_USER:=mcpulse_admin}"
: "${DB_CLASS:=db.t3.micro}"
: "${DB_ENGINE_VERSION:=16}"
: "${DB_STORAGE:=20}"
: "${WEB_SG:=mcpulse-web-sg}"
: "${DB_SG:=mcpulse-db-sg}"
: "${DB_SUBNET_GROUP:=mcpulse-db-subnet-group}"
: "${EC2_NAME:=mcpulse-server}"
: "${EC2_TYPE:=t3.small}"
: "${EC2_AMI_NAME:=ubuntu/images/hvm-ssd/ubuntu-noble-24.04-amd64-server-*}"
: "${APP_DIR:=/home/ubuntu/mcpulse}"
: "${STATE_FILE:=${HOME}/.mcpulse/aws-lab-state.env}"

export AWS_PROFILE AWS_REGION

# ------------------------------------------------------------------- utilities

log()  { printf '\033[1;34m[%s]\033[0m %s\n' "$(date +%H:%M:%S)" "$*"; }
warn() { printf '\033[1;33m[%s] WARN:\033[0m %s\n' "$(date +%H:%M:%S)" "$*" >&2; }
fail() { printf '\033[1;31m[%s] ERROR:\033[0m %s\n' "$(date +%H:%M:%S)" "$*" >&2; exit 1; }
ok()   { printf '\033[1;32m[%s] OK:\033[0m %s\n' "$(date +%H:%M:%S)" "$*"; }

aws_() { aws --profile "$AWS_PROFILE" --region "$AWS_REGION" "$@"; }

require_aws() {
  command -v aws >/dev/null 2>&1 ||
    fail "AWS CLI is not installed. Install it with: brew install awscli"

  local error
  if ! error="$(aws_ sts get-caller-identity 2>&1)"; then
    if printf '%s' "$error" | grep -qiE "ExpiredToken|expired|InvalidClientTokenId"; then
      fail "The Learner Lab credentials for profile '$AWS_PROFILE' have expired.
Refresh them from the lab page (AWS Credentials panel) and store them with:
    aws-lab-login"
    fi
    fail "Credentials for profile '$AWS_PROFILE' are not valid: $error"
  fi
}

# Fails loudly instead of silently switching account or region.
assert_identity() {
  # The expected account defaults to the one recorded in the state file, so a
  # new lab session with a different account is detected instead of silently
  # deploying into the wrong place.
  local expected_account="${EXPECTED_ACCOUNT_ID:-${MCPULSE_ACCOUNT_ID:-}}"
  local identity
  identity="$(aws_ sts get-caller-identity --output json)" ||
    fail "Unable to resolve the AWS identity for profile '$AWS_PROFILE'."
  ACCOUNT_ID="$(printf '%s' "$identity" | python3 -c 'import json,sys; print(json.load(sys.stdin)["Account"])')"
  CALLER_ARN="$(printf '%s' "$identity" | python3 -c 'import json,sys; print(json.load(sys.stdin)["Arn"])')"
  if [[ -n "$expected_account" && "$ACCOUNT_ID" != "$expected_account" ]]; then
    fail "Active account '$ACCOUNT_ID' does not match the expected '$expected_account'. Refusing to continue."
  fi
  log "Identity: $CALLER_ARN (account $ACCOUNT_ID, region $AWS_REGION)"
}

load_state() {
  if [[ -f "$STATE_FILE" ]]; then
    # shellcheck disable=SC1090
    source "$STATE_FILE"
  fi
}

save_state() {
  mkdir -p "$(dirname "$STATE_FILE")"
  chmod 700 "$(dirname "$STATE_FILE")"
  {
    echo "# MCPulse AWS lab state - regenerated by scripts/aws/*.sh. No secrets."
    echo "MCPULSE_STATE_WRITTEN_AT=$(date -u +%Y-%m-%dT%H:%M:%SZ)"
    echo "MCPULSE_ACCOUNT_ID=${ACCOUNT_ID:-}"
    echo "MCPULSE_REGION=${AWS_REGION}"
    echo "MCPULSE_EC2_INSTANCE_ID=${EC2_INSTANCE_ID:-}"
    echo "MCPULSE_EC2_PUBLIC_IP=${EC2_PUBLIC_IP:-}"
    echo "MCPULSE_DB_IDENTIFIER=${DB_IDENTIFIER}"
    echo "MCPULSE_DB_ENDPOINT=${DB_ENDPOINT:-}"
    echo "MCPULSE_VPC_ID=${VPC_ID:-}"
    echo "MCPULSE_WEB_SG_ID=${WEB_SG_ID:-}"
    echo "MCPULSE_DB_SG_ID=${DB_SG_ID:-}"
    echo "MCPULSE_DB_SUBNET_GROUP=${DB_SUBNET_GROUP}"
    echo "MCPULSE_S3_BUCKET=${S3_BUCKET:-}"
  } > "$STATE_FILE"
  chmod 600 "$STATE_FILE"
}

# ------------------------------------------------------------------- discovery

default_vpc_id() {
  aws_ ec2 describe-vpcs \
    --filters "Name=isDefault,Values=true" "Name=state,Values=available" \
    --query "Vpcs[0].VpcId" --output text 2>/dev/null
}

# Subnets that can reach the internet.
#
# A subnet is only publicly routable when the route table it uses has an
# Internet Gateway default route. In the default VPC the subnets attach to the
# main route table, which has no per-subnet association entry, so the check is
# done on the VPC level and combined with the auto-assign-public-ip flag.
public_subnet_ids() {
  local vpc="$1"
  local igw_routes
  igw_routes="$(aws_ ec2 describe-route-tables \
    --filters "Name=vpc-id,Values=$vpc" \
    --query "RouteTables[?Routes[?DestinationCidrBlock=='0.0.0.0/0' && GatewayId!=null]].RouteTableId" \
    --output text 2>/dev/null | tr '\t' '\n' | sed '/^$/d')"
  [[ -n "$igw_routes" ]] || return 0
  aws_ ec2 describe-subnets \
    --filters "Name=vpc-id,Values=$vpc" "Name=map-public-ip-on-launch,Values=true" \
    --query "Subnets[].SubnetId" --output text 2>/dev/null | tr '\t' '\n' | sed '/^$/d'
}

# Availability zones covered by the given subnets (one AZ per line).
subnet_availability_zones() {
  aws_ ec2 describe-subnets \
    --filters "Name=vpc-id,Values=$1" \
    --query "Subnets[].AvailabilityZone" --output text 2>/dev/null | tr '\t' '\n' | sed '/^$/d' | sort -u
}

# Lists "<subnet-id> <availability-zone>" pairs for the VPC.
#
# The subnet list and the availability zone list are read from the same call
# so they can never disagree. A short retry loop protects against a transient
# truncated response from the API.
discover_subnet_az_pairs() {
  local vpc="$1" attempt=1 result="" count=0
  while [[ $attempt -le 3 ]]; do
    result="$(aws_ ec2 describe-subnets \
      --filters "Name=vpc-id,Values=$vpc" \
      --query "Subnets[].[SubnetId,AvailabilityZone]" --output text 2>/dev/null \
      | tr '\t' ' ' | sed '/^$/d')"
    count="$(printf '%s\n' "$result" | grep -c '[a-z0-9-]\+' || true)"
    if [[ "$count" -ge 2 ]]; then
      printf '%s\n' "$result"
      return 0
    fi
    warn "Subnet discovery returned $count subnet(s) for $vpc, retrying (attempt $attempt/3)"
    sleep 5
    attempt=$((attempt + 1))
  done
  printf '%s\n' "$result"
  return 1
}

# First public subnet in the given AZ, or the first public subnet overall.
public_subnet_in() {
  local vpc="$1" az="${2:-}"
  local candidates
  candidates="$(public_subnet_ids "$vpc")"
  [[ -n "$candidates" ]] || return 1
  if [[ -n "$az" ]]; then
    while read -r subnet; do
      [[ -z "$subnet" ]] && continue
      local subnet_az
      subnet_az="$(aws_ ec2 describe-subnets --filters "Name=subnet-id,Values=$subnet" \
        --query "Subnets[0].AvailabilityZone" --output text 2>/dev/null)"
      if [[ "$subnet_az" == "$az" ]]; then
        printf '%s' "$subnet"; return 0
      fi
    done <<< "$candidates"
  fi
  printf '%s' "$(head -n1 <<< "$candidates")"
}

# ------------------------------------------------------------------- utilities

wait_for() {
  local description="$1" timeout="$2"; shift 2
  local deadline=$(( $(date +%s) + timeout ))
  log "Waiting for $description (timeout ${timeout}s)..."
  while (( $(date +%s) < deadline )); do
    if "$@" >/dev/null 2>&1; then
      ok "$description"
      return 0
    fi
    sleep 5
  done
  fail "Timed out after ${timeout}s waiting for $description"
}
